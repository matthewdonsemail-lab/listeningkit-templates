"""Face-collage patches (Nick Jayk style) on the face stills AND on their style-variation flashes: rectangles of
the face cut from the same image and pasted back enlarged / offset. The variations share the original's
composition, so one set of boxes per still fits every style. Crops into images/collage/<still>/<style>_p<i>.png
and writes plugins/faceCollage.jsx. Patches follow their layer (the still or the flash) through expressions
(parenting comes out flipped in EffectCraft). Box: (x0, y0, w, h) fractions of the image; scale; offset fractions."""
import os
import subprocess

ROOT = "C:/Users/0/.buzz/REPOS/listeningkit-templates/images/"
STILLS = {
    "img 2 every conversation": ("shadow/02_every_conversation", "02_every_conversation", [
        ((.40, .37, .10, .10), 1.7, (-.05, 0)), ((.46, .57, .14, .10), 1.0, (.04, .01))]),
    "img 3 youve ever had": ("beats/03_youve_ever_had", "03_youve_ever_had", [
        ((.22, .44, .16, .15), 1.6, (-.04, .03)), ((.50, .46, .18, .14), 1.0, (.03, -.02)),
        ((.40, .82, .15, .11), 1.25, (-.02, 0))]),
    "img 9 vector search": ("beats/10_vector_search", "10_vector_search", [
        ((.65, .38, .12, .10), 1.7, (.04, -.01)), ((.57, .58, .13, .09), 1.0, (-.03, .01))]),
    "img 10 the way you actually": ("beats/11_the_way_you_actually", "11_the_way_you_actually", [
        ((.40, .58, .16, .13), 1.5, (.05, 0)), ((.36, .45, .11, .11), 1.0, (-.03, 0))]),
    "img 11 talk": ("shadow/12_talk", "12_talk", [
        ((.19, .36, .13, .12), 1.6, (-.02, -.03)), ((.67, .45, .13, .15), 1.3, (-.04, 0))]),
    "shot only moat": ("Blue Noir Only Moat", "Blue_Noir_Only_Moat", [
        ((.36, .39, .10, .10), 1.7, (-.05, .02)), ((.44, .51, .09, .09), 1.2, (.03, 0))]),
}
STYLES = ["hyperreal", "ps2", "oil", "magritte", "clay", "ukiyoe", "macpaint", "crtcollage"]


def dims(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "stream=width,height", "-of", "csv=p=0", path],
                         capture_output=True, text=True).stdout.strip().split(",")
    return int(out[0]), int(out[1])


js = ["// Generated by make_collage.py. Do not edit by hand.",
      "function findComp(n){ for (var i=1;i<=app.project.numItems;i++){var it=app.project.item(i); if(it instanceof CompItem && it.name===n) return it;} return null; }",
      "function findFile(path){ for (var i=1;i<=app.project.numItems;i++){var it=app.project.item(i); if(it instanceof FootageItem && it.file && it.file.fsName.replace(/\\\\/g,'/').toLowerCase()===path.toLowerCase()) return it;} return null; }",
      "function byName(c,n){ for (var k=1;k<=c.numLayers;k++) if(c.layer(k).name===n) return c.layer(k); return null; }",
      "var c=findComp('Intro 1');",
      "for (var k=c.numLayers;k>=1;k--) if(/^patch /.test(c.layer(k).name)) c.layer(k).remove();",
      # host: the layer the patch sits on (still or flash); (cx,cy) patch centre in host source pixels; W,H host size
      "function patch(host,file,i,cx,cy,W,H,s,ox,oy,flash){",
      "  var Hl=byName(c,host); if(!Hl){ writeLn('missing '+host); return; }",
      "  var src=findFile(file)||app.project.importFile(new ImportOptions(new File(file)));",
      "  var L=c.layers.add(src); L.name='patch '+host+' '+i; L.moveBefore(Hl);",
      "  L.startTime=Hl.inPoint; L.inPoint=flash?Hl.inPoint:Hl.inPoint+0.10+0.16*i; L.outPoint=Hl.outPoint;",
      "  var ref='thisComp.layer(\"'+host+'\").transform';",
      "  L.property('Transform').property('Scale').expression='var s='+ref+'.scale;[s[0]*'+s+',s[1]*'+s+']';",
      # the stills re-cut once halfway (the patches jump); the 3-frame flashes hold the jumped layout
      "  var j=flash?'1':'(time>inPoint+(outPoint-inPoint)*0.5?1:0)';",
      "  L.property('Transform').property('Position').expression='var T='+ref+',k=T.scale[0]/100,j='+j+';'+",
      "    '[T.position[0]+('+(cx-W/2)+'+'+ox+'*(1+j*0.6))*k,T.position[1]+('+(cy-H/2)+'+'+oy+'+j*'+(i%2?-12:12)+')*k]';",
      "  var e=L.property('Effects').addProperty('ec.color.exposure'); e.property('master').property('exposure').setValue(i%2?-0.25:0.3);",
      "}"]
n = 0
for layer, (src, stem, patches) in STILLS.items():
    hosts = [(layer, ROOT + src + ".png", "orig", False)]
    hosts += [("var %s %s" % (layer, st), ROOT + "variants/%s/%s.png" % (stem, st), st, True) for st in STYLES]
    for host, img, tag, flash in hosts:
        if not os.path.exists(img):
            continue
        W, H = dims(img)
        os.makedirs(ROOT + "collage/" + stem, exist_ok=True)
        for i, ((x0, y0, w, h), s, (ox, oy)) in enumerate(patches):
            px, py, pw, ph = int(x0 * W), int(y0 * H), int(w * W), int(h * H)
            f = ROOT + "collage/%s/%s_p%d.png" % (stem, tag, i)
            subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", img, "-vf",
                            "crop=%d:%d:%d:%d" % (pw, ph, px, py), f], check=True)
            # only flashes that exist in the edit get patches; the JS skips missing hosts quietly for those
            js.append("%sif(byName(c,%r)) patch(%r,%r,%d,%.1f,%.1f,%d,%d,%.2f,%.1f,%.1f,%s);" % (
                "", host, host, f, i, px + pw / 2, py + ph / 2, W, H, s, ox * W, oy * H, "true" if flash else "false"))
            n += 1
js.append("writeLn('collage patches placed');")
open("C:/Users/0/.buzz/REPOS/listeningkit-templates/textAnimations/plugins/faceCollage.jsx", "w").write("\n".join(js) + "\n")
print(n, "patch crops")
