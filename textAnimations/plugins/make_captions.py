SKIP = [(12.0, 16.97), (26.94, 33.40), (54.70, 99)]  # intro card / platform tour show their own words; the moat words exist


def skip(t):
    return any(a <= t < b for a, b in SKIP)


out = ["// Generated by make_captions.py: the VO in each shot's negative space. Do not edit by hand.",
       "function findComp(n){ for (var i=1;i<=app.project.numItems;i++){var it=app.project.item(i); if(it instanceof CompItem && it.name===n) return it;} return null; }",
       "function byName(c,n){ for (var k=1;k<=c.numLayers;k++) if(c.layer(k).name===n) return c.layer(k); return null; }",
       "var c=findComp('Intro 1');",
       "for (var k=c.numLayers;k>=1;k--) if(/^cap /.test(c.layer(k).name)) c.layer(k).remove();",
       "var under=byName(c,'Adjustment Layer 1');",
       "var J={L:ParagraphJustification.LEFT_JUSTIFY,C:ParagraphJustification.CENTER_JUSTIFY,R:ParagraphJustification.RIGHT_JUSTIFY};",
       "function cap(name,full,list,tin,tout,x,y,j,size){",
       "  var T=c.layers.addText(full); T.name=name; T.moveAfter(under); T.startTime=0; T.inPoint=tin; T.outPoint=tout;",
       "  var st=T.property('Source Text'), td=st.value;",
       "  td.font='Satoshi'; td.fauxBold=true; td.fontSize=size; td.tracking=size>=100?10:140; td.fillColor=[1,1,1]; td.justification=J[j];",
       "  st.setValue(td);",
       "  st.expression='var w='+list+',s=\"\";for(var i=0;i<w.length;i++)if(time>=w[i][1])s+=(s?\" \":\"\")+w[i][0];s';",
       "  T.property('Transform').property('Position').setValue([x,y]);",
       "  var ex=T.property('Effects').addProperty('ec.color.exposure'); ex.property('master').property('exposure').setValue(2.4);",  # lifted so it survives the grade and the CRT colorize
       "  T.property('Effects').addProperty('ADBE Glo2');",
       "}"]
from caption_layouts import LAYOUTS

n = 0
for s in SHOTS:
    a, b, x, y, j, note = s
    ws = [w for w in words if a - 0.05 <= w[0] < b and not skip(w[0])]
    if not ws:
        continue
    lst = [[w[2].upper().replace('"', ''), max(round(w[0], 2), a)] for w in ws]
    layout = LAYOUTS[n]
    n += 1
    # each layout line is its own text layer, taking the next words of the VO in order
    k = 0
    for li, (text, lx, ly, size, lj) in enumerate(layout):
        cnt = len(text.split())
        part = lst[k:k + cnt]
        k += cnt
        got = " ".join(p[0] for p in part)
        if got != text:
            sys.exit("cap %02d line %d: layout says %r, VO says %r" % (n, li + 1, text, got))
        out.append("cap(%s,%s,%s,%.2f,%.2f,%d,%d,%s,%d); // %s" % (
            json.dumps("cap %02d.%d" % (n, li + 1)), json.dumps(text), json.dumps(json.dumps(part)), a, b, lx, ly,
            json.dumps(lj), size, note))
    if k != len(lst):
        sys.exit("cap %02d: layout covers %d of %d words" % (n, k, len(lst)))
out.append("writeLn('captions: %d');" % n)
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print(n, "captions")




