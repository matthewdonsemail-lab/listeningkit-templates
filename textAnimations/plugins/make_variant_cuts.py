"""Writes plugins/variantCuts.jsx: inside each story still's shot, its style variations (images/variants/<still>)
flash in for 3 frames at a time between frames of the original. Short shots get 3 variations, longer ones 5;
the set rotates from shot to shot so neighbours use different styles. Each flash copies its still's scale and
position through expressions, so it rides the still's push and drift. Removes the old rectangle collage patches."""
import os

ROOT = "C:/Users/0/.buzz/REPOS/listeningkit-templates/images/variants/"
ORDER = ["hyperreal", "ps2", "oil", "magritte", "clay", "ukiyoe", "macpaint", "crtcollage"]
LAYERS = [("img 1 log ingests", "01_log_ingests"), ("img 2 every conversation", "02_every_conversation"),
          ("img 3 youve ever had", "03_youve_ever_had"), ("img 4 a voice profile", "05_a_voice_profile"),
          ("img 5 of you", "06_of_you"), ("img 6 local models", "07_local_models"), ("img 7 re rank", "08_re_rank"),
          ("img 8 embed", "09_embed"), ("img 9 vector search", "10_vector_search"),
          ("img 10 the way you actually", "11_the_way_you_actually"), ("img 11 talk", "12_talk"),
          ("img 12 time back", "13_time_back"), ("shot only moat", "Blue_Noir_Only_Moat")]
js = ["// Generated by make_variant_cuts.py. Do not edit by hand.",
      "function findComp(n){ for (var i=1;i<=app.project.numItems;i++){var it=app.project.item(i); if(it instanceof CompItem && it.name===n) return it;} return null; }",
      "function findFile(path){ for (var i=1;i<=app.project.numItems;i++){var it=app.project.item(i); if(it instanceof FootageItem && it.file && it.file.fsName.replace(/\\\\/g,'/').toLowerCase()===path.toLowerCase()) return it;} return null; }",
      "function byName(c,n){ for (var k=1;k<=c.numLayers;k++) if(c.layer(k).name===n) return c.layer(k); return null; }",
      "var c=findComp('Intro 1'), F=1/30;",
      "for (var k=c.numLayers;k>=1;k--) if(/^(patch|var) /.test(c.layer(k).name)) c.layer(k).remove();",
      "function flash(still,file,style,t0,frames){",
      "  var S=byName(c,still); if(!S){ writeLn('missing '+still); return; }",
      "  var src=findFile(file)||app.project.importFile(new ImportOptions(new File(file)));",
      "  var L=c.layers.add(src); L.name='var '+still+' '+style; L.moveBefore(S);",
      "  L.startTime=t0; L.inPoint=t0; L.outPoint=t0+frames*F;",
      # follows the still's push and drift through expressions (parenting comes out flipped in EffectCraft)
      "  var r=S.source.width/src.width, ref='thisComp.layer(\"'+still+'\").transform';",
      "  L.property('Transform').property('Scale').expression='var s='+ref+'.scale;[s[0]*'+r+',s[1]*'+r+']';",
      "  L.property('Transform').property('Position').expression=ref+'.position';",
      "}",
      "var D={};"]
for n, (layer, stem) in enumerate(LAYERS):
    have = [s for s in ORDER if os.path.exists(ROOT + "%s/%s.png" % (stem, s))]
    if not have:
        continue
    rot = have[n % len(have):] + have[:n % len(have)]
    js.append("(function(){ var S=byName(c,%r); if(!S) return; var a=S.inPoint, b=S.outPoint;" % layer)
    js.append("  var n=(b-a)>1.5?5:3, t=a+6*F;")  # first 6 frames are the original, then var/orig alternating
    js.append("  var st=%r;" % rot)
    js.append("  for (var i=0;i<n && t+3*F<=b-2*F;i++){ flash(%r,'%s%s/'+st[i]+'.png',st[i],t,3); t+=5*F; }" % (layer, ROOT, stem))
    js.append("})();")
js.append("writeLn('variant cuts placed');")
open("C:/Users/0/.buzz/REPOS/listeningkit-templates/textAnimations/plugins/variantCuts.jsx", "w").write("\n".join(js) + "\n")
print("ok")

