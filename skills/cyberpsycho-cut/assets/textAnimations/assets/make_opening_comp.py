"""The launch film's intro (before cyberpunk) as EffectCraft pre-comps, from layers, and the "launch film" comp that
plays it into cyberpunk with the sound. Reads assets/opening_edit.json (the cut: since 2026-11-15 matt's FilmCraft cut,
written by sync_opening_from_filmcraft.py, each clip's file in "src" with its FilmCraft Motion; older cuts name a "still"
in projects/opening/), and writes:
  projects/opening/layers/dust.png   drifting gold dust specks
  plugins/openingDawn.jsx            the build script (generated: edit this file, not it)

Comps (Project panel folder "opening parts"), rebuilt in place like the outro:
  launch film           the intro, then cyberpunk, with matt's VO (projects/cyberpunk/audio.mp3) and the music bed
                        (assets/audio/launch_music.wav, make_launch_sound_trailer.py)
  opening               every shot nested in order, its camera move keyed on the nested layer, and the white flash
                        into cyberpunk at the end
    opening NN <shot>   one pre-comp per clip, in track then time order (track 2 nests on top): the still or video
                        with its Motion; older cuts add dust drifting through the light, or the GPT-3 text written on
                        the whiteboard as an editable text layer
Comps from an earlier cut that are no longer in opening_edit.json are removed on a full build.
Usage:
  python assets/make_opening_comp.py [--only "opening 03 gpt-3"]
  effectcraft-cli --project textAnimations.ecproj script plugins/openingDawn.jsx --save"""
import json
import os
import sys

import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..")).replace("\\", "/") + "/"
OPR = "projects/opening/"
ED = json.load(open(os.path.join(HERE, "opening_edit.json")))
ONLY = sys.argv[sys.argv.index("--only") + 1] if "--only" in sys.argv else None

# dust specks, larger than the frame so they can drift
rng = np.random.default_rng(11)
DW, DH = 2400, 1400
dust = np.zeros((DH, DW, 4), np.float32)
for _ in range(900):
    x, y = rng.integers(0, DW), rng.integers(0, DH)
    r = rng.choice([1, 1, 1, 2, 2, 3, 5])
    a = rng.uniform(0.25, 1.0) * (0.45 if r >= 3 else 1.0)
    cv2.circle(dust, (int(x), int(y)), int(r), (150 * a, 215 * a, 255 * a, 255 * a), -1, cv2.LINE_AA)
os.makedirs(ROOT + OPR + "layers", exist_ok=True)
cv2.imwrite(ROOT + OPR + "layers/dust.png", np.clip(cv2.GaussianBlur(dust, (0, 0), 1.1), 0, 255).astype(np.uint8))

shots = []
for k, s in enumerate(ED["shots"]):
    s = dict(s, comp="opening %02d %s" % (k, s["name"]), frames=s["out"] - s["in"])
    shots.append(s)
data = {"root": ROOT, "op": OPR, "fps": ED["fps"], "frames": ED["frames"], "shots": shots, "flash": ED["flash"],
        "cyberStart": ED.get("cyberStart", ED["frames"]),
        "music": "textAnimations/assets/audio/launch_music.wav", "vo": "projects/cyberpunk/audio.mp3"}

JSX = r"""// GENERATED by assets/make_opening_comp.py: edit that script (or assets/opening_edit.json) and rerun it.
// The launch film's intro (NARRATIVE_SCRIPT.md lines 1-3) as pre-comps from layers, and "launch film" playing it
// into cyberpunk with the sound. Rebuilt in place; ONLY rebuilds just one comp.
var D = __DATA__;
var ONLY = __ONLY__;
function want(n){ return ONLY===null || ONLY===n; }
var F=D.fps, ROOT=D.root;
function findFile(path){ for (var i=1;i<=app.project.numItems;i++){var it=app.project.item(i); if(it instanceof FootageItem && it.file && it.file.fsName.replace(/\\/g,"/").toLowerCase()===path.toLowerCase()) return it;} return null; }
var seen={};
function foot(rel){ var p=(rel.charAt(1)===":"?rel:ROOT+rel); if(seen[p]) return seen[p]; var it=findFile(p); if(it) it.replace(new File(p)); else it=app.project.importFile(new ImportOptions(new File(p))); seen[p]=it; return it; }
function compNamed(n){ for (var i=1;i<=app.project.numItems;i++){ var it=app.project.item(i); if(it instanceof CompItem && it.name===n) return it; } return null; }
var FOLDER=null; for (var i=1;i<=app.project.numItems;i++){ var it=app.project.item(i); if(it instanceof FolderItem && it.name==="opening parts") FOLDER=it; }
if(!FOLDER) FOLDER=app.project.items.addFolder("opening parts");
function comp(name,frames){ var c=compNamed(name);
  if(c){ for (var k=c.numLayers;k>=1;k--) c.layer(k).remove(); c.duration=frames/F; return c; }
  c=app.project.items.addComp(name,1920,1080,1,frames/F,F); c.parentFolder=FOLDER; return c; }
function span(L,a,b){ L.startTime=0; L.inPoint=a/F; L.outPoint=b/F; }
function keys(prop,list,o){ o=o||0; for (var k=0;k<list.length;k++) prop.setValueAtTime((list[k][0]+o)/F,list[k][1]); }
function T(L,n){ return L.property("Transform").property(n); }
function layer(c,rel,name,a,b){ var L=c.layers.add(foot(rel)); L.name=name; span(L,a,b); return L; }

// an earlier cut's shot comps (and the old split) go, on a full build
if(ONLY===null){ var keep={}; for (var s=0;s<D.shots.length;s++) keep[D.shots[s].comp]=1;
  for (var i=app.project.numItems;i>=1;i--){ var it=app.project.item(i);
    if(it instanceof CompItem && it.name.indexOf("opening ")===0 && !keep[it.name]) it.remove(); } }

// --- each shot's own pre-comp
for (var s=0;s<D.shots.length;s++){ var sh=D.shots[s]; if(!want(sh.comp)) continue;
  var c=comp(sh.comp,sh.frames), n=sh.frames;
  if(sh.src){ // matt's FilmCraft cut: the clip's own file with its Motion (anchor, position, scale)
    var Ls=c.layers.add(foot(sh.src)); Ls.name=sh.name; Ls.startTime=-(sh.sourceIn||0)/F; Ls.inPoint=0; Ls.outPoint=n/F;
    T(Ls,"Anchor Point").setValue(sh.anchor); T(Ls,"Position").setValue(sh.position); T(Ls,"Scale").setValue([sh.scale,sh.scale]); }
  else layer(c,D.op+sh.still,sh.name,0,n);
  if(sh.dust){ var Dl=layer(c,D.op+"layers/dust.png","dust",0,n); Dl.blendingMode=BlendingMode.ADD;
    keys(T(Dl,"Opacity"),[[0,60]]); keys(T(Dl,"Position"),[[0,[960,560]],[n,[1010,500]]]); }
  if(sh.text){ // written on the board in marker, editable
    var tl=c.layers.addText(sh.text); tl.name=sh.text; span(tl,0,n);
    try{ var td=tl.property("Source Text").value; td.font="Schoolbell"; td.fontSize=230; td.fillColor=[0.08,0.16,0.42];
      td.applyFill=true; td.applyStroke=false; td.justification=ParagraphJustification.CENTER_JUSTIFY; tl.property("Source Text").setValue(td); }catch(x){}
    keys(T(tl,"Position"),[[0,[960,600]]]); keys(T(tl,"Rotation"),[[0,-3]]); keys(T(tl,"Opacity"),[[0,88]]); }
}

// --- the intro: every shot in order, the camera moves on the nested layers, the white flash into cyberpunk
function move(L,m,n,o){ var s=T(L,"Scale"), p=T(L,"Position");
  if(m==="push") keys(s,[[0,[100,100]],[n,[107,107]]],o);
  else if(m==="drift"){ keys(s,[[0,[105,105]]],o); keys(p,[[0,[940,540]],[n,[980,540]]],o); }
  else if(m==="slide"){ keys(s,[[0,[106,106]]],o); keys(p,[[0,[995,540]],[n,[925,540]]],o); }
}
if(want("opening")){
  var O=comp("opening",D.frames);
  for (var s=0;s<D.shots.length;s++){ var sh=D.shots[s], src=compNamed(sh.comp); if(!src) throw new Error("no comp "+sh.comp);
    var L=O.layers.add(src); L.name=sh.comp; L.startTime=sh["in"]/F; L.inPoint=sh["in"]/F; L.outPoint=sh.out/F;
    move(L,sh.move,sh.frames,sh["in"]); }
  if(D.flash){ var a=D.flash[0], b=D.flash[1];
  var X=O.layers.addSolid([0,0,0],"flash into cyberpunk",1920,1080,1); X.adjustmentLayer=true; span(X,a,b);
  var ex=X.property("Effects").addProperty("ec.color.exposure");
  keys(ex.property("Master").property("Exposure"),[[a,0],[b-3,2.5],[b,6]]); }
}

// --- the launch film: the intro, then cyberpunk, with the sound
if(want("launch film")){
  var cy=compNamed("cyberpunk"), op=compNamed("opening"); if(!cy||!op) throw new Error("need the opening and cyberpunk comps");
  // as long as the VO; cyberpunk starts on "split", and whatever comes after it (the ending) is still to build
  var vo=foot(D.vo), CF=Math.round(cy.duration*F), N=Math.max(Math.ceil(vo.duration*F)+15,(D.cyberStart===undefined?D.frames:D.cyberStart)+CF);
  var LF=comp("launch film",N);
  var la=LF.layers.add(op); la.name="opening"; span(la,0,D.frames);
  var lb=LF.layers.add(cy); lb.name="cyberpunk"; var cs=(D.cyberStart===undefined?D.frames:D.cyberStart); lb.startTime=cs/F; lb.inPoint=D.frames/F; lb.outPoint=(cs+CF)/F;
  var lv=LF.layers.add(vo); lv.name="vo"; span(lv,0,N);
  var lm=LF.layers.add(foot(D.music)); lm.name="music"; span(lm,0,N);
  LF.parentFolder=app.project.rootFolder;
}
writeLn("opening: rebuilt "+(ONLY===null?"everything":"'"+ONLY+"'")+", in place");
"""

with open(os.path.join(HERE, "..", "plugins", "openingDawn.jsx"), "w", encoding="ascii", newline="\n") as fh:
    fh.write(JSX.replace("__DATA__", json.dumps(data, ensure_ascii=True)).replace("__ONLY__", json.dumps(ONLY)))
print("wrote plugins/openingDawn.jsx")
